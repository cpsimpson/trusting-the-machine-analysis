# Manuscript statistics export ---------------------------------------------
#
# Formats results for the manuscript and writes them as LaTeX definitions,
# so the manuscript can use \stat{key} instead of typed numbers.
#
#   \defstat{e1-anthro-human-low-t}{11.87}
#
# Values that include a relation (p values, small effect sizes) carry it:
# fmt_p() gives "< .001" or "= .180", so the manuscript writes $p \stat{key}$.

# Number with fixed decimals; negative zero is printed as 0.
fmt_num <- function(x, digits = 2) {
  out <- formatC(round(x, digits), format = "f", digits = digits)
  sub("^-(0\\.0+)$", "\\1", out)
}

# APA style for values bounded by 1 (r, p, omega squared): no leading zero.
fmt_unit <- function(x, digits = 2) sub("^(-?)0\\.", "\\1.", fmt_num(x, digits))

# p value with its relation: "< .001" or "= .180".
fmt_p <- function(p, digits = 3) {
  if (p < .001) "< .001" else paste("=", fmt_unit(p, digits))
}

# Omega squared with its relation: "< .01" or "= .12".
fmt_omega <- function(w) if (w < .01) "< .01" else paste("=", fmt_unit(w, 2))

# Confidence interval "[lo, hi]".
fmt_ci <- function(lo, hi, digits = 2, unit = FALSE) {
  f <- if (unit) fmt_unit else fmt_num
  sprintf("[%s, %s]", f(lo, digits), f(hi, digits))
}

# Collects key/value pairs and writes them as \defstat lines.
stat_store <- function() {
  values <- list()
  list(
    add = function(key, value) {
      if (!grepl("^[a-z0-9-]+$", key)) stop("Invalid stat key: ", key)
      if (!is.null(values[[key]])) stop("Duplicate stat key: ", key)
      values[[key]] <<- as.character(value)
    },
    write = function(file) {
      dir.create(dirname(file), recursive = TRUE, showWarnings = FALSE)
      lines <- c("% Generated by export-manuscript-stats.R. Do not edit by hand.",
                 sprintf("\\defstat{%s}{%s}", names(values), unlist(values)))
      writeLines(lines, file)
      invisible(length(values))
    }
  )
}

# One-way ANOVA with omega squared and the error mean square (MSE).
anova_stats <- function(data, dv) {
  fit <- stats::lm(stats::as.formula(paste(dv, "~ Condition")), data = data)
  a <- stats::anova(fit)
  ss_b <- a$`Sum Sq`[1]; ss_w <- a$`Sum Sq`[2]; df_b <- a$Df[1]; df_w <- a$Df[2]
  mse <- ss_w / df_w
  list(F = a$`F value`[1], df1 = df_b, df2 = df_w, p = a$`Pr(>F)`[1], mse = mse,
       omega2 = (ss_b - df_b * mse) / (ss_b + ss_w + mse))
}

# Adds Welch t, Bonferroni-corrected p, Cohen's d and CI for a vs. b.
add_pairwise <- function(store, data, dv, a, b, key, n_comparisons = 3) {
  w <- welch_with_d(data, dv, a, b)
  store$add(paste0(key, "-t"), fmt_num(w$t))
  store$add(paste0(key, "-df"), fmt_num(w$df))
  store$add(paste0(key, "-p"), fmt_p(min(1, w$p * n_comparisons)))
  store$add(paste0(key, "-d"), fmt_num(w$d))
  store$add(paste0(key, "-ci"), fmt_ci(w$d_low, w$d_high))
  invisible(w)
}

add_anova <- function(store, data, dv, key, p_digits = 3) {
  s <- anova_stats(data, dv)
  store$add(paste0(key, "-f"), fmt_num(s$F))
  store$add(paste0(key, "-df"), sprintf("%d, %d", s$df1, s$df2))
  store$add(paste0(key, "-mse"), fmt_num(s$mse))
  store$add(paste0(key, "-p"), fmt_p(s$p, p_digits))
  store$add(paste0(key, "-omega"), fmt_omega(s$omega2))
  invisible(s)
}

add_descriptives <- function(store, data, dv, condition, key) {
  x <- data[[dv]][data$Condition == condition]
  store$add(paste0(key, "-n"), length(x))
  store$add(paste0(key, "-m"), fmt_num(mean(x)))
  store$add(paste0(key, "-sd"), fmt_num(stats::sd(x)))
}

# B [CI] and p for one contrast of a robust_condition_model() result.
add_b <- function(store, estimates, key, contrast = "High vs. Low", with_ci = TRUE) {
  e <- estimates[estimates$contrast == contrast, ]
  store$add(paste0(key, "-b"), fmt_num(e$B))
  if (with_ci) store$add(paste0(key, "-ci"), fmt_ci(e$ci_low, e$ci_high))
  store$add(paste0(key, "-p"), fmt_p(e$p))
}

add_r <- function(store, row, key) {
  store$add(paste0(key, "-r"), fmt_unit(row$r))
  store$add(paste0(key, "-df"), row$df)
  store$add(paste0(key, "-p"), fmt_p(row$p))
  store$add(paste0(key, "-ci"), fmt_ci(row$ci_low, row$ci_high, unit = TRUE))
}

# Body rows of a robustness table (Tables 2 and 4), one \makecell per cell.
robustness_table_rows <- function(rows) {
  cell <- function(r) sprintf("\\makecell{$%s$ $%s$\\\\$p %s$}",
                              fmt_num(r$B), fmt_ci(r$ci_low, r$ci_high), fmt_p(r$p))
  specs <- unique(rows$specification)
  vapply(specs, function(s) {
    r <- rows[rows$specification == s, ]
    sprintf("%s & %d & %s & %s & %s \\\\", s, r$n[1],
            cell(r[r$outcome == "author", ]), cell(r[r$outcome == "content", ]),
            cell(r[r$outcome == "difference", ]))
  }, character(1), USE.NAMES = FALSE)
}

# Experiment 1 results (Section 4.2) and Table 2 ----------------------------
#
# Condition labels: Low = low, Medium = high, High = human.
export_experiment1_stats <- function(store, s1, s1_cc) {
  conds <- c(low = "Low", high = "Medium", human = "High")

  # Manipulation check
  add_anova(store, s1, "anthro", "e1-anthro-anova")
  for (nm in names(conds)) add_descriptives(store, s1, "anthro", conds[[nm]], paste0("e1-anthro-", nm))
  add_pairwise(store, s1, "anthro", "High", "Low", "e1-anthro-human-low")
  add_pairwise(store, s1, "anthro", "High", "Medium", "e1-anthro-human-high")
  add_pairwise(store, s1, "anthro", "Low", "Medium", "e1-anthro-low-high")

  # Likeability and perceived intelligence
  add_anova(store, s1, "likeability", "e1-like-anova")
  add_anova(store, s1, "competence", "e1-intel-anova")
  human_vs_ai <- do.call(rbind, lapply(c("likeability", "competence"), function(v) rbind(
    welch_with_d(s1, v, "High", "Low"), welch_with_d(s1, v, "High", "Medium"))))
  ai_vs_ai <- do.call(rbind, lapply(c("likeability", "competence"), function(v)
    welch_with_d(s1, v, "Medium", "Low")))
  store$add("e1-like-intel-human-d-min", fmt_num(min(human_vs_ai$d)))
  store$add("e1-like-intel-human-d-max", fmt_num(max(human_vs_ai$d)))
  store$add("e1-like-intel-ai-absd-max", fmt_num(max(abs(ai_vs_ai$d))))

  # Content and author trust
  add_anova(store, s1, "content", "e1-content-anova")
  add_pairwise(store, s1, "content", "High", "Low", "e1-content-human-low")
  add_pairwise(store, s1, "content", "Low", "Medium", "e1-content-low-high")
  add_anova(store, s1, "author", "e1-author-anova")
  for (nm in names(conds)) add_descriptives(store, s1, "author", conds[[nm]], paste0("e1-author-", nm))
  add_pairwise(store, s1, "author", "High", "Low", "e1-author-human-low")
  add_pairwise(store, s1, "author", "High", "Medium", "e1-author-human-high")
  add_pairwise(store, s1, "author", "Low", "Medium", "e1-author-low-high")

  # Author vs. content trust: mixed-model interaction (= difference-score test)
  diff_test <- trust_difference_test(s1)
  df_resid <- nrow(s1) - 3
  store$add("e1-interaction-df", df_resid)
  store$add("e1-interaction-human-low-t", fmt_num(diff_test["ConditionHigh", "t value"]))
  store$add("e1-interaction-human-low-p", fmt_p(diff_test["ConditionHigh", "Pr(>|t|)"]))
  store$add("e1-interaction-high-low-t", fmt_num(diff_test["ConditionMedium", "t value"]))
  store$add("e1-interaction-high-low-p", fmt_p(diff_test["ConditionMedium", "Pr(>|t|)"]))
  std <- composite_standardized_models(s1)
  add_b(store, std$difference, "e1-std-diff-human-low")

  # Validated scales
  add_anova(store, s1, "author_meti", "e1-meti-anova")
  add_pairwise(store, s1, "author_meti", "High", "Low", "e1-meti-human-low")
  add_anova(store, s1, "content_app", "e1-msgcred-anova", p_digits = 2)
  add_pairwise(store, s1, "content_app", "High", "Low", "e1-msgcred-human-low")
  validated_diff <- trust_difference_test(s1, "author_meti", "content_app")
  store$add("e1-interaction-validated-t", fmt_num(validated_diff["ConditionHigh", "t value"]))
  store$add("e1-interaction-validated-p", fmt_p(validated_diff["ConditionHigh", "Pr(>|t|)"]))
  for (v in c("expertise", "integrity", "benevolence")) {
    add_b(store, robust_condition_model(s1, v, character(0))$estimates,
          paste0("e1-", v, "-human-low"), with_ci = FALSE)
  }
  add_anova(store, s1, "writing_quality", "e1-wq-anova", p_digits = 2)

  # Equivalence tests
  tost_high <- tost_table(s1, "content", "Low", "Medium")
  tost_human <- tost_table(s1, "content", "High", "Low")
  t30 <- tost_high[tost_high$bound_d == 0.30, ]
  store$add("e1-tost-content-low-high-d", fmt_num(t30$d))
  store$add("e1-tost-content-low-high-ci90", fmt_ci(t30$ci90_low, t30$ci90_high))
  store$add("e1-tost-content-low-high-p30", fmt_p(t30$p_tost))
  store$add("e1-tost-content-human-low-ci90", fmt_ci(tost_human$ci90_low[1], tost_human$ci90_high[1]))

  # Robustness (Table 2 and text)
  rows <- dplyr::bind_rows(
    robustness_row(s1, "Primary"),
    robustness_row(s1, "Validated scales only", scores = "validated"),
    robustness_row(s1_cc, "Complete cases only"),
    robustness_row(s1[s1$Reread != 1, ], "Excluding participants who reread"),
    robustness_row(s1, "Covariate-adjusted", covariates = robustness_covariates))
  primary <- rows[rows$specification == "Primary", ]
  adjusted <- rows[rows$specification == "Covariate-adjusted", ]
  store$add("e1-primary-author-b", fmt_num(primary$B[primary$outcome == "author"]))
  store$add("e1-primary-content-b", fmt_num(primary$B[primary$outcome == "content"]))
  store$add("e1-adjusted-content-b", fmt_num(adjusted$B[adjusted$outcome == "content"]))
  store$add("e1-adjusted-content-p", fmt_p(adjusted$p[adjusted$outcome == "content"]))
  store$add("e1-adjusted-diff-b", fmt_num(adjusted$B[adjusted$outcome == "difference"]))
  store$add("e1-adjusted-diff-p", fmt_p(adjusted$p[adjusted$outcome == "difference"]))
  sci_only <- robust_condition_model(s1, "content", "science_frequency")$estimates
  no_sci <- robust_condition_model(s1, "content", setdiff(robustness_covariates, "science_frequency"))$estimates
  add_b(store, sci_only, "e1-content-sci-only", with_ci = FALSE)
  add_b(store, no_sci, "e1-content-no-sci", with_ci = FALSE)
  high_low_rows <- dplyr::bind_rows(
    robustness_row(s1, "Primary", contrast = "Medium vs. Low"),
    robustness_row(s1, "Validated", scores = "validated", contrast = "Medium vs. Low"),
    robustness_row(s1_cc, "Complete", contrast = "Medium vs. Low"),
    robustness_row(s1[s1$Reread != 1, ], "Reread", contrast = "Medium vs. Low"),
    robustness_row(s1, "Adjusted", covariates = robustness_covariates, contrast = "Medium vs. Low"))
  store$add("e1-high-low-robust-p-min", fmt_unit(floor(min(high_low_rows$p) * 100) / 100))
  table_rows <- robustness_table_rows(rows)

  # Correlations
  cs <- correlation_summary(s1)
  for (pair in cs$pooled$pair) {
    add_r(store, cs$pooled[cs$pooled$pair == pair, ], paste0("e1-r-", gsub("_", "-", pair)))
    add_r(store, cs$within[cs$within$pair == pair, ], paste0("e1-rw-", gsub("_", "-", pair)))
  }
  store$add("e1-williams-within-t", fmt_num(cs$williams_within$t))
  store$add("e1-williams-within-df", cs$williams_within$df)
  store$add("e1-williams-within-p", fmt_p(cs$williams_within$p))

  list(table2_rows = table_rows)
}
