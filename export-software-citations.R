# Exports software versions and citations ----------------------------------
#
# Writes, for the R installation that runs it:
#   outputs/manuscript/software.tex       \defstat{r-version}{...} and
#                                         \defstat{pkg-<name>-version}{...}
#   outputs/manuscript/software.bib       BibTeX entries keyed R-base, R-<name>,
#                                         in APA 7 form (see apa_entry())
#   outputs/manuscript/session-info.txt   full sessionInfo() after loading the
#                                         analysis scripts, for the record
# If MANUSCRIPT_DIR is set, the files are also copied to
# <MANUSCRIPT_DIR>/generated/. Run it in the same R installation as
# export-manuscript-stats.R so the versions match the reported results.
#
#   Rscript export-software-citations.R
#   MANUSCRIPT_DIR=../trusting-the-machine-manuscript Rscript export-software-citations.R

# Packages cited in the manuscript, and what they are used for.
cited_packages <- c(
  pwr      = "power analyses",
  psych    = "Cronbach's alpha",
  lme4     = "linear mixed-effects models",
  lmerTest = "tests for mixed-model coefficients",
  sandwich = "HC3 and clustered standard errors",
  lmtest   = "coefficient tests with robust standard errors",
  car      = "joint tests of condition effects",
  ggplot2  = "figures",
  ggpubr   = "significance brackets in figures"
)

# Which entry of citation(<package>) to use when a package lists several
# (matched against the title). Packages not listed use the first entry.
citation_choice <- c(sandwich = "Various Versatile Variances")

out_dir <- file.path("outputs", "manuscript")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

stat_key <- function(pkg) paste0("pkg-", tolower(gsub("[^A-Za-z0-9]", "", pkg)), "-version")
bib_key <- function(pkg) if (pkg == "base") "R-base" else paste0("R-", pkg)

pick_citation <- function(pkg) {
  cits <- if (pkg == "base") utils::citation() else utils::citation(pkg)
  i <- 1
  if (pkg %in% names(citation_choice)) {
    titles <- vapply(seq_along(cits), function(j) cits[[j]]$title, character(1))
    i <- grep(citation_choice[[pkg]], titles, fixed = TRUE)[1]
    if (is.na(i)) stop("No citation of ", pkg, " matches '", citation_choice[[pkg]], "'")
  }
  cits[[i]]
}

pkg_version <- function(pkg) {
  if (pkg == "base") paste(R.version$major, R.version$minor, sep = ".")
  else utils::packageDescription(pkg)$Version
}

# Rewrites an R-generated BibTeX entry for APA 7 (biblatex-apa and apa.csl):
#   - a @Manual (R itself or a package's reference manual) becomes @Software
#     with a version field, which prints "(Version x) [Computer software]",
#     instead of a note "R package version x" (which can be out of date), and
#     its organization becomes the publisher;
#   - the package name and quoted package names in the title are braced, so
#     sentence casing keeps them as written (lmerTest, 'ggplot2');
#   - a spelled-out edition ("Third") becomes a number, printed "3rd ed.".
apa_entry <- function(lines, pkg, version) {
  if (grepl("^@Manual\\{", lines[1], ignore.case = TRUE)) {
    lines[1] <- sub("^@Manual\\{", "@Software{", lines[1], ignore.case = TRUE)
    lines <- lines[!grepl("^\\s*note = \\{R package version", lines)]
    lines <- sub("^(\\s*)organization = ", "\\1publisher = ", lines)
    lines <- append(lines, sprintf("  version = {%s},", version), after = 1)
  }
  title <- grep("^\\s*title = \\{", lines)
  if (length(title) == 1 && pkg != "base") {
    lines[title] <- sub(sprintf("= \\{%s(:| )", pkg), sprintf("= {{%s}\\1", pkg), lines[title])
    lines[title] <- gsub("'([A-Za-z][A-Za-z0-9.]*)'", "{'\\1'}", lines[title])
  }
  editions <- c(Second = "2", Third = "3", Fourth = "4", Fifth = "5", Sixth = "6")
  edition <- grep("^\\s*edition = \\{", lines)
  for (i in edition) {
    word <- sub("^\\s*edition = \\{([^}]*)\\}.*$", "\\1", lines[i])
    if (word %in% names(editions)) lines[i] <- sub(word, editions[[word]], lines[i], fixed = TRUE)
  }
  lines
}

bibtex_entry <- function(pkg) {
  lines <- format(pick_citation(pkg), style = "Bibtex")
  lines <- unlist(strsplit(lines, "\n"))
  lines[1] <- sub("\\{,?$", paste0("{", bib_key(pkg), ","), lines[1])
  lines <- apa_entry(lines, pkg, pkg_version(pkg))
  # Some packages give a person as a braced literal ({{William Revelle}}), which
  # BibTeX prints as is. Unbrace personal names; keep organizations braced.
  author <- grep("^\\s*author = \\{\\{[^{}]*\\}\\},?$", lines)
  for (i in author) {
    name <- sub("^\\s*author = \\{\\{([^{}]*)\\}\\},?$", "\\1", lines[i])
    if (!grepl("Team|Foundation|Group|Consortium|Project", name)) {
      lines[i] <- sub("\\{\\{([^{}]*)\\}\\}", "{\\1}", lines[i])
    }
  }
  c(lines, "")
}

# Versions
r_version <- pkg_version("base")
defs <- c("% Generated by export-software-citations.R. Do not edit by hand.",
          sprintf("\\defstat{r-version}{%s}", r_version))
for (pkg in names(cited_packages)) {
  defs <- c(defs, sprintf("\\defstat{%s}{%s}", stat_key(pkg), pkg_version(pkg)))
}
writeLines(defs, file.path(out_dir, "software.tex"))

# Citations
bib <- c("% Generated by export-software-citations.R. Do not edit by hand.", "",
         bibtex_entry("base"), unlist(lapply(names(cited_packages), bibtex_entry)))
writeLines(bib, file.path(out_dir, "software.bib"))

# Full session record, with the analysis scripts loaded
suppressPackageStartupMessages({
  library(tidyverse)
  library(haven)
  invisible(utils::capture.output({
    source("./scripts/data-loading.R", local = TRUE)
    source("./scripts/data-cleaning.R", local = TRUE)
    source("./scripts/analysis-robustness.R", local = TRUE)
    source("./scripts/analysis-revision.R", local = TRUE)
  }))
  for (pkg in names(cited_packages)) loadNamespace(pkg)
})
writeLines(utils::capture.output(utils::sessionInfo()), file.path(out_dir, "session-info.txt"))

cat("Wrote R", r_version, "and", length(cited_packages), "package versions and citations to", out_dir, "\n")

manuscript_dir <- Sys.getenv("MANUSCRIPT_DIR")
if (nzchar(manuscript_dir)) {
  target <- file.path(manuscript_dir, "generated")
  dir.create(target, recursive = TRUE, showWarnings = FALSE)
  file.copy(file.path(out_dir, c("software.tex", "software.bib", "session-info.txt")), target,
            overwrite = TRUE)
  cat("Copied to", target, "\n")
}
