# Exports manuscript statistics and tables -----------------------------------
#
# Writes outputs/manuscript/stats.tex (\defstat definitions) and
# outputs/manuscript/tables/*.tex (table bodies). If MANUSCRIPT_DIR is set,
# the files are also copied to <MANUSCRIPT_DIR>/generated/.
#
#   Rscript export-manuscript-stats.R
#   MANUSCRIPT_DIR=../trusting-the-machine-manuscript Rscript export-manuscript-stats.R

suppressPackageStartupMessages({
  library(tidyverse)
  library(haven)
})
source("./scripts/data-loading.R", local = TRUE)
source("./scripts/data-cleaning.R", local = TRUE)
source("./scripts/analysis-robustness.R", local = TRUE)
source("./scripts/analysis-revision.R", local = TRUE)
source("./scripts/manuscript-stats.R", local = TRUE)

quiet <- function(expr) {
  out <- NULL
  invisible(utils::capture.output(out <- suppressMessages(suppressWarnings(expr))))
  out
}

out_dir <- file.path("outputs", "manuscript")
dir.create(file.path(out_dir, "tables"), recursive = TRUE, showWarnings = FALSE)

s1_raw <- quiet(prepare_raw_data("s1"))
s1_filtered <- quiet(clean_data(s1_raw, "s1"))
s1 <- quiet(build_study_data("s1", raw = s1_raw))
s1_cc <- quiet(build_study_data("s1", impute = FALSE, raw = s1_raw))
s1_cc <- s1_cc[s1_cc$ResponseId %in% complete_case_ids(s1_filtered, "s1"), ]

store <- stat_store()
e1 <- quiet(export_experiment1_stats(store, s1, s1_cc))

n <- store$write(file.path(out_dir, "stats.tex"))
writeLines(c("% Generated by export-manuscript-stats.R. Do not edit by hand.", e1$table2_rows),
           file.path(out_dir, "tables", "e1-alternative-specifications.tex"))
cat("Wrote", n, "statistics and 1 table to", out_dir, "\n")

manuscript_dir <- Sys.getenv("MANUSCRIPT_DIR")
if (nzchar(manuscript_dir)) {
  target <- file.path(manuscript_dir, "generated")
  dir.create(file.path(target, "tables"), recursive = TRUE, showWarnings = FALSE)
  file.copy(file.path(out_dir, "stats.tex"), target, overwrite = TRUE)
  file.copy(list.files(file.path(out_dir, "tables"), full.names = TRUE),
            file.path(target, "tables"), overwrite = TRUE)
  cat("Copied to", target, "\n")
}
